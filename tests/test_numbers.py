import pytest

from holostts_wyoming.pipeline import StepConfig, build_chain

num = build_chain(["numbers"], StepConfig())

CASES = [
    ("У вітальні 21 °C.", "У вітальні двадцять один градус."),
    ("22 °C", "двадцять два градуси"),
    ("25 °C", "двадцять п'ять градусів"),
    ("11 °C", "одинадцять градусів"),
    ("21.5 °C", "двадцять одна ціла п'ять десятих градуса"),
    ("-3 °C", "мінус три градуси"),
    ("Яскравість 40%", "Яскравість сорок відсотків"),
    ("1 хвилина", "одна хвилина"),
    ("2 хвилини", "дві хвилини"),
    ("5 хвилин", "п'ять хвилин"),
    ("Таймер на 1 хвилину", "Таймер на одну хвилину"),
    ("Таймер на 21 хвилину", "Таймер на двадцять одну хвилину"),
    ("на 2 години", "на дві години"),
    ("Зараз 15:30", "Зараз п'ятнадцята тридцять"),
    ("07:05", "сьома нуль п'ять"),
    ("3:00", "третя нуль нуль"),
    ("Увімкнено 3 світильники", "Увімкнено три світильники"),
    ("Без чисел.", "Без чисел."),
]


@pytest.mark.parametrize("text,expected", CASES)
def test_numbers(text, expected):
    assert num(text) == expected
